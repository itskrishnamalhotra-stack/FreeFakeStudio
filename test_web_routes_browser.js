async (page) => {
  page.setDefaultTimeout(15000);
  page.setDefaultNavigationTimeout(15000);
  const check = (value, message) => { if (!value) throw new Error(message); };
  const path = () => new URL(page.url()).pathname;
  const readyChat = () => page.waitForFunction(() => {
    const chat = document.querySelector('.chat-layout');
    return chat?.getAttribute('aria-busy') === 'false' && chat.getAttribute('data-route') === location.pathname;
  });
  await page.setViewportSize({width:1440,height:960});
  await page.goto('http://127.0.0.1:7867/');
  await page.waitForURL('**/chats/new');
  await readyChat();
  await page.getByRole('button', {name:'New chat', exact:true}).click();
  check(path() === '/chats/new', 'Create should reuse the blank draft');
  await page.getByRole('textbox', {name:'Image prompt', exact:true}).fill('Saved route conversation A');
  await page.getByRole('button', {name:'Generate image', exact:true}).click();
  await page.waitForURL(url => /^\/chats\/[^/]+$/.test(url.pathname) && url.pathname !== '/chats/new');
  await page.getByAltText('Generated image', {exact:true}).waitFor();
  await readyChat();
  const a = path();
  await page.getByRole('textbox', {name:'Image prompt', exact:true}).fill('Unsent route draft A');
  await page.getByRole('button', {name:'New chat', exact:true}).click();
  await page.waitForURL('**/chats/new');
  await readyChat();
  await page.getByRole('textbox', {name:'Image prompt', exact:true}).fill('Saved route conversation B');
  await page.getByRole('button', {name:'Generate image', exact:true}).click();
  await page.waitForURL(url => /^\/chats\/[^/]+$/.test(url.pathname) && url.pathname !== '/chats/new');
  await page.getByAltText('Generated image', {exact:true}).waitFor();
  const b = path();
  await page.getByRole('textbox', {name:'Image prompt', exact:true}).fill('Unsent route draft B');
  await page.goBack();
  await page.waitForURL('**' + a);
  await readyChat();
  check(await page.getByRole('textbox', {name:'Image prompt', exact:true}).inputValue() === 'Unsent route draft A', 'Back lost or mixed the first draft');
  await page.goForward();
  await page.waitForURL('**' + b);
  await readyChat();
  check(await page.getByRole('textbox', {name:'Image prompt', exact:true}).inputValue() === 'Unsent route draft B', 'Forward lost or mixed the second draft');
  await page.reload();
  await page.getByAltText('Generated image', {exact:true}).waitFor();
  check(path() === b, 'Reload opened a different main chat');
  await page.getByRole('button', {name:'Avatar Studio', exact:true}).click();
  await page.waitForURL('**/avatars');
  await page.reload();
  await page.getByRole('button', {name:'Open avatar Enhancement QA', exact:true}).click();
  await page.waitForURL(/\/avatars\/[^/]+\/console\/[^/]+$/);
  await readyChat();
  const avatarBase = path().split('/console/')[0];
  await page.getByRole('button', {name:'New avatar chat', exact:true}).click();
  await page.waitForURL('**' + avatarBase + '/console/new');
  await readyChat();
  const avatarDraft = path();
  let avatarChat = avatarDraft;
  check(avatarChat.startsWith(avatarBase + '/console/'), 'New avatar chat escaped its scope');
  await page.getByRole('textbox', {name:'Image prompt', exact:true}).fill('Avatar route draft');
  await page.getByRole('tab', {name:'Gallery', exact:true}).click();
  await page.waitForURL('**' + avatarBase + '/gallery/generations');
  await page.goBack();
  await page.waitForURL('**' + avatarChat);
  await readyChat();
  check(await page.getByRole('textbox', {name:'Image prompt', exact:true}).inputValue() === 'Avatar route draft', 'Avatar draft lost on Back');
  await page.getByRole('button', {name:'Generate image', exact:true}).click();
  await page.waitForURL(url => url.pathname.startsWith(avatarBase + '/console/') && url.pathname !== avatarDraft);
  avatarChat = path();
  await page.getByAltText('Generated image', {exact:true}).waitFor();
  await page.getByRole('tab', {name:'Gallery', exact:true}).click();
  const sections = page.getByRole('tablist', {name:'Gallery sections', exact:true});
  await sections.getByRole('tab', {name:/^Enhancements /}).click();
  await page.waitForURL('**' + avatarBase + '/gallery/enhancements');
  await sections.getByRole('tab', {name:/^Resources /}).click();
  await page.waitForURL('**' + avatarBase + '/gallery/resources');
  await page.goBack();
  check(path().endsWith('/gallery/enhancements'), 'Back did not restore gallery category');
  await page.goForward();
  await page.reload();
  await page.getByRole('combobox', {name:'Resource type', exact:true}).waitFor();
  check(path().endsWith('/gallery/resources'), 'Resource deep-link reload failed');
  await page.getByRole('tab', {name:'Body', exact:true}).click();
  await page.waitForURL('**' + avatarBase + '/body');
  await page.reload();
  await page.getByRole('tab', {name:'Body', exact:true}).waitFor();
  check(await page.getByRole('tab', {name:'Body', exact:true}).getAttribute('aria-selected') === 'true', 'Body deep-link reload failed');
  await page.goto('http://127.0.0.1:7867' + avatarChat + '#access=local-routing-test');
  await page.getByAltText('Generated image', {exact:true}).waitFor();
  check(new URL(page.url()).hash === '', 'Access fragment was not cleared');
  check(path() === avatarChat, 'Authentication lost the deep link');
  await page.goto('http://127.0.0.1:7867' + avatarBase + '/console/' + b.split('/').at(-1));
  await page.getByRole('heading', {name:'Page unavailable', exact:true}).waitFor();
  await page.goto('http://127.0.0.1:7867/avatars/no-such-avatar/gallery/resources');
  await page.getByRole('heading', {name:'Page unavailable', exact:true}).waitFor();
  await page.goto('http://127.0.0.1:7867/no-such-page');
  await page.getByRole('heading', {name:'Page unavailable', exact:true}).waitFor();
  await page.goto('http://127.0.0.1:7867/chats/no-such-chat');
  await page.getByRole('heading', {name:'Page unavailable', exact:true}).waitFor();
  await page.goto('http://127.0.0.1:7867' + avatarBase + '/gallery/resources');
  await page.getByRole('combobox', {name:'Resource type', exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Routed mobile page overflows');
  await page.screenshot({path:'output/playwright/routing-mobile-resources.png'});
  await page.setViewportSize({width:1440,height:960});
  await page.screenshot({path:'output/playwright/routing-desktop-resources.png'});
  return {passed:true, checks:['root canonical URL','new main chat routes','Back/Forward drafts','reload history','avatar library route','avatar-scoped new chats','avatar draft recovery','gallery category Back/Forward','gallery refresh','body refresh','deep-link access fragment','cross-scope rejection','missing resources and routes','mobile layout']};
}
