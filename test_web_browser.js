async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const fixture = 'results/qa/supplied-preview.png';
  await page.setViewportSize({width:1440,height:960});
  await page.reload();
  await page.getByRole('button',{name:'Create',exact:true}).click();
  const before = await page.getByAltText('Generated image',{exact:true}).count();
  await page.getByRole('textbox',{name:'Image prompt',exact:true}).fill('Browser mock generation regression');
  await page.getByRole('button',{name:'Generate image',exact:true}).click();
  await page.waitForFunction(count => document.querySelectorAll('img[alt="Generated image"]').length > count, before);
  check(await page.getByRole('textbox',{name:'Image prompt',exact:true}).inputValue()==='', 'Composer did not clear');
  await page.locator('input[type=file]').first().setInputFiles(fixture);
  await page.getByRole('button',{name:'Add reference (1/4)',exact:true}).waitFor();
  await page.locator('input[type=file]').first().setInputFiles(fixture);
  await page.getByRole('button',{name:'Add reference (2/4)',exact:true}).waitFor();
  await page.getByRole('button',{name:'Reference',exact:true}).nth(1).click();
  check(await page.getByRole('button',{name:'Canvas',exact:true}).count()===1,'Canvas state not represented');
  await page.getByRole('button',{name:'Move left',exact:true}).nth(1).click();
  check(await page.locator('.attachment').first().getByRole('button',{name:'Canvas',exact:true}).count()===1,'Canvas did not follow reorder');
  await page.getByRole('button',{name:'Remove image',exact:true}).nth(1).click();
  check(await page.getByRole('button',{name:'Canvas',exact:true}).count()===1,'Removing another attachment lost canvas');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('slider',{name:'Steps',exact:true}).fill('17');
  check(await page.getByRole('spinbutton',{name:'Steps value',exact:true}).inputValue()==='17','Slider number mismatch');
  const fill = await page.getByRole('slider',{name:'Steps',exact:true}).evaluate(el=>el.style.getPropertyValue('--fill'));
  check(Math.abs(parseFloat(fill)-16/49*100)<.01,'Slider fill mismatch');
  await page.getByRole('combobox',{name:'Mask',exact:true}).selectOption('Manual Paint');
  await page.getByRole('button',{name:'Paint mask',exact:true}).click();
  await page.getByRole('dialog',{name:'Paint edit mask'}).waitFor();
  const box = await page.locator('.mask-canvas').boundingBox();
  check(box.width>100&&box.height>100,'Mask editor blank');
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.4);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.6,box.y+box.height*.6,{steps:12});
  await page.mouse.up();
  await page.getByRole('button',{name:'Use mask',exact:true}).click();
  await page.getByRole('button',{name:'Edit painted mask',exact:true}).waitFor();
  await page.getByRole('dialog',{name:'Generation settings'}).getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('Z-Image Turbo');
  check(await page.getByRole('button',{name:/Add reference/}).count()===0,'Text-only model exposes reference upload');
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('FLUX.2-klein 4B');
  await page.getByRole('button',{name:'Enhancement QA Ready',exact:true}).click();
  await page.getByRole('tab',{name:'Console',exact:true}).click();
  await page.screenshot({path:'output/playwright/react-console-desktop.png'});
  const footer = await page.locator('.composer').boundingBox();
  check(footer.y+footer.height<=962&&footer.y>400,'Console footer outside viewport');
  await page.getByRole('tab',{name:'Gallery',exact:true}).click();
  await page.getByRole('button',{name:'Create batch',exact:true}).waitFor();
  await page.locator('.gallery-image').last().scrollIntoViewIfNeeded();
  const scroll = await page.locator('.gallery-view').evaluate(el=>el.scrollTop);
  await page.locator('.gallery-image').last().click();
  await page.getByRole('dialog',{name:'Photograph',exact:true}).waitFor();
  await page.getByAltText('Full-size photograph',{exact:true}).evaluate(img=>img.complete?Promise.resolve():new Promise(resolve=>{img.onload=resolve;img.onerror=resolve}));
  const modal = await page.getByRole('dialog',{name:'Photograph',exact:true}).boundingBox();
  check(modal.y>=0&&modal.y+modal.height<=962,'Gallery modal outside current viewport');
  await page.screenshot({path:'output/playwright/react-gallery-modal-desktop.png'});
  await page.keyboard.press('Escape');
  check(Math.abs(await page.locator('.gallery-view').evaluate(el=>el.scrollTop)-scroll)<3,'Modal changed gallery scroll');
  await page.getByRole('button',{name:'Pipeline',exact:true}).click();
  await page.getByRole('dialog',{name:'Reference pipeline',exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('tab',{name:'Console',exact:true}).click();
  await page.screenshot({path:'output/playwright/react-console-mobile.png'});
  let dimensions = await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
  check(dimensions.scroll<=dimensions.width,'Mobile overflow');
  const mobileFooter = await page.locator('.composer').boundingBox();
  check(mobileFooter.y+mobileFooter.height<=846,'Mobile composer cut off');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.screenshot({path:'output/playwright/react-settings-mobile.png'});
  await page.keyboard.press('Escape');
  await page.getByRole('tab',{name:'Gallery',exact:true}).click();
  await page.screenshot({path:'output/playwright/react-gallery-mobile.png'});
  await page.locator('.gallery-image').first().click();
  await page.screenshot({path:'output/playwright/react-gallery-modal-mobile.png'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:320,height:740});
  dimensions = await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
  check(dimensions.scroll<=dimensions.width,'320px overflow');
  await page.getByRole('button',{name:'Light theme',exact:true}).click();
  await page.screenshot({path:'output/playwright/react-gallery-small-light.png'});
  await page.getByRole('button',{name:'Dark theme',exact:true}).click();
  console.log(JSON.stringify({passed:true,checks:['chat result and clearing','append and remove attachments','canvas reordering','slider fill','manual mask','model-specific controls','docked composer','gallery modal and scroll','pipeline','390px mobile','320px light theme']}));
}
